# ── 다중 제품 비교 해설 ────────────────────────────────────────
# 영기님 제품 비교 결과(성분 포함 관계·주의사항)를 받아 자연어로 풀어 설명한다.
#
# ⚠️ 핵심 제약: 화장품 전성분은 배합순만 공개되고 배합비율(%)은 공개되지 않는다.
#    따라서 "어느 제품이 더 효과적/안전하다"는 우열 판정은 불가능하며 금지한다.
#    성분 구성의 '차이'는 설명하되 '우열'은 말하지 않는다.
