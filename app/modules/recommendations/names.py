"""성분명 정규화 — 파이프라인 전 단계가 공유하는 단일 키 생성기.

④ 후보 집계·⑤ 안전성 필터·⑦ 응답 조립이 같은 문자열로 성분을 식별해야 해서
독립 모듈로 둔다. 어느 한 단계가 정규화를 빠뜨리면 안전 검사가 조용히 우회된다.
"""

import re


def normalize_ingredient_name(name: str) -> str:
    """성분명을 상수 조회·중복 제거·환각 검사가 공유하는 하나의 키로 만든다.

    `rec_efficacy.name_kr` 에는 개행·괄호 주석이 붙은 값이 있다 — 2,270행 중 개행
    12·괄호 15건. 예: `"레티놀\\n(비타민 A)"`, `"레틴알(레티날)"`. 원본 문자열로
    `PREGNANCY_CONTRAINDICATED` 를 조회하면 **임신 금기 레티놀이 필터를 그대로
    통과한다**. 알레르기 25종·고시 배지 조회, LLM 프롬프트의 후보 목록, 환각 차단의
    허용 집합도 전부 같은 이유로 빗나간다.

    부분 문자열 매칭 대신 정규화 후 정확 일치를 쓰는 이유는 `플로레틴`·
    `글리시레티닉애씨드` 처럼 "레티/레틴"을 포함하지만 레티노이드가 아닌 성분이
    실제 데이터에 있어 오탐이 나기 때문이다.
    """
    collapsed = re.sub(r"\s+", " ", name).strip()
    head = re.split(r"[(\[]", collapsed)[0].strip()
    return head or collapsed
